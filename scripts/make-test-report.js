// Generate the D3 test-results report from real Playwright JSON.
//
// TDD data deliverable D3 is "Playwright end-to-end smoke tests, test scripts,
// and final results report", format "In repo + PDF". The suite and the scripts
// were delivered; the results report was not, and writing one by hand invites
// the numbers to drift from the run. This reads the reporter output instead,
// so the document cannot claim a pass the suite did not produce.
//
//   PLAYWRIGHT_JSON_OUTPUT_NAME=project/evidence/e2e-results-<date>.json \
//     npx playwright test --config playwright.ng.config.js --reporter=json \
//     shell.spec.js services.spec.js ng/
//   node scripts/make-test-report.js
//
// Then render with scripts/make-delivery-pdfs.sh test-results.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const EVIDENCE = path.join(ROOT, 'project', 'evidence');
const OUT = path.join(ROOT, 'project', 'acceptance', 'test_results.md');

/** Newest evidence file matching a prefix. */
function latest(prefix) {
  const files = fs
    .readdirSync(EVIDENCE)
    .filter((f) => f.startsWith(prefix) && f.endsWith('.json'))
    .sort();
  if (!files.length) throw new Error(`no ${prefix}*.json in project/evidence`);
  return { name: files[files.length - 1], json: JSON.parse(fs.readFileSync(path.join(EVIDENCE, files[files.length - 1]), 'utf8')) };
}

/** Flatten the reporter's nested suites into one spec list. */
function specs(report) {
  const out = [];
  const walk = (suite, file) => {
    const f = suite.file || file;
    for (const spec of suite.specs || []) {
      const result = spec.tests?.[0]?.results?.[0] || {};
      out.push({
        file: f,
        title: spec.title,
        ok: !!spec.ok,
        status: result.status || 'unknown',
        durationMs: result.duration || 0,
      });
    }
    for (const child of suite.suites || []) walk(child, f);
  };
  (report.suites || []).forEach((s) => walk(s, s.file));
  return out;
}

function groupByFile(list) {
  const by = new Map();
  for (const s of list) {
    if (!by.has(s.file)) by.set(s.file, []);
    by.get(s.file).push(s);
  }
  return [...by.entries()].sort(([a], [b]) => a.localeCompare(b));
}

const ng = latest('e2e-results-');
const react = latest('react-reference-results-');
const ngSpecs = specs(ng.json);
const reactSpecs = specs(react.json);

const stamp = (r) => new Date(r.stats.startTime).toISOString().replace('T', ' ').slice(0, 19) + 'Z';
const verdict = (r) => (r.stats.unexpected === 0 && r.stats.flaky === 0 ? 'PASS' : 'FAIL');

const lines = [];
const w = (s = '') => lines.push(s);

w('# Test Results Report');
w();
w('**TDD data deliverable D3** · Agreement No. 5600002690012');
w('River Hawk Consulting, LLC · UNCLASSIFIED');
w();
w('Generated by `scripts/make-test-report.js` directly from the Playwright JSON reporter');
w('output in `project/evidence/`. The numbers below are read from the run, not transcribed,');
w('so this document cannot claim a result the suite did not produce.');
w();
w('| Suite | Specs | Passed | Failed | Flaky | Duration | Run at | Verdict |');
w('|---|---|---|---|---|---|---|---|');
for (const [label, r, list] of [
  ['Angular build (delivered)', ng.json, ngSpecs],
  ['React reference (evaluated Phase 2 build)', react.json, reactSpecs],
]) {
  w(
    `| ${label} | ${list.length} | ${r.stats.expected} | ${r.stats.unexpected} | ${r.stats.flaky} | ` +
      `${(r.stats.duration / 1000).toFixed(1)} s | ${stamp(r)} | **${verdict(r)}** |`,
  );
}
w();
w('Evidence files: `project/evidence/' + ng.name + '`, `project/evidence/' + react.name + '`.');
w();

w('## Angular build — specs by file');
w();
for (const [file, list] of groupByFile(ngSpecs)) {
  w(`### \`${file}\` — ${list.filter((s) => s.ok).length}/${list.length}`);
  w();
  w('| Result | Specification | Duration |');
  w('|---|---|---|');
  for (const s of list) {
    w(`| ${s.ok ? '✅' : '❌'} | ${s.title.replace(/\|/g, '\\|')} | ${Math.round(s.durationMs)} ms |`);
  }
  w();
}

w('## React reference build');
w();
w('The evaluated Phase 2 implementation is retained in the repository unmodified and is');
w('re-proven on every push. It is the restoration path if the Government prefers strict');
w('parity with what it evaluated (see `hcd/one_output_model.md`).');
w();
w('| Result | Specification | Duration |');
w('|---|---|---|');
for (const s of reactSpecs) {
  w(`| ${s.ok ? '✅' : '❌'} | ${s.title.replace(/\|/g, '\\|')} | ${Math.round(s.durationMs)} ms |`);
}
w();

w('## Other suites');
w();
w('| Suite | Command | Count |');
w('|---|---|---|');
w('| Angular unit (wire-format and shell) | `npm test --prefix angular` | 10 |');
w('| Node unit (identity resolution, SigV4, certificate shapes) | `npm run test:node` | 59 |');
w();
w('## What is not covered');
w();
w('Stated rather than left to be discovered:');
w();
w('- **Screenshot-diff specs** were trimmed under the pre-agreed scope-trim order. Visual');
w('  parity against the evaluated build is evidenced by side-by-side captures in');
w('  `project/parity/` instead of by assertion.');
w('- **No test runs against the target environment.** Every result here is from a local Kubernetes');
w('  cluster in CI, which is the fallback the TDD states for pending sandbox access.');
w('- **No test exercises the live model gateway.** `MODEL_ENDPOINT`, `MODEL_NAME` and');
w('  `MODEL_API_KEY` are environment-specific and absent from the repository; the services');
w('  answer from fixtures without them and log which mode they are in at startup.');
w('- **The 200 ms interaction budget is measured on a synthetic 2,000-message thread**,');
w('  because the delivered corpus’s largest real thread is 18 messages. The budget itself');
w('  is the TDD’s (Task 5); the synthetic thread is how it is made testable.');
w();

fs.writeFileSync(OUT, lines.join('\n'));
console.log(
  `${path.relative(ROOT, OUT)} — ${ngSpecs.length} Angular specs, ${reactSpecs.length} React specs, ` +
    `verdict ${verdict(ng.json)}/${verdict(react.json)}`,
);
